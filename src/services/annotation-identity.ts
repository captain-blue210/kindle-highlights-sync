import { Buffer } from "buffer";
import { createHash } from "crypto";
import type { Highlight } from "../models";

/** Compatibility only: never use this 16-bit value as a new annotation identity. */
export function kindleHash(text: string): string {
	let a = 0,
		b = 0;
	for (const byte of Buffer.from(text.toLowerCase(), "utf8")) {
		a = (a + byte) % 255;
		b = (b + a) % 255;
	}
	return String((b << 8) | a);
}
export const normalizeSourceText = (text: string) =>
	text.replace(/\s+/g, " ").trim();
export const digest = (text: string) =>
	createHash("sha256").update(text, "utf8").digest("hex");
export function annotationLocation(location: string | undefined): string {
	const digits = location?.match(/\d+$/)?.[0];
	return digits
		? digits.replace(/^0+(?=\d)/, "")
		: normalizeSourceText(location ?? "");
}
export function annotationText(h: Highlight): string {
	return h.text?.trim() ? h.text : (h.note ?? "");
}
export function annotationKey(h: Highlight, asin: string): string {
	if (h.parentAnnotationKey)
		return (
			"s1-" +
			digest(
				JSON.stringify([
					1,
					asin,
					annotationLocation(h.location),
					"attached-note",
					h.parentAnnotationKey,
					digest(normalizeSourceText(annotationText(h))),
				]),
			)
		);
	// h.id is generated by older parsers. Amazon IDs are not trusted until stability is verified.
	return (
		"s1-" +
		digest(
			JSON.stringify([
				1,
				asin,
				annotationLocation(h.location),
				h.text?.trim() ? "highlight" : "note",
				digest(normalizeSourceText(annotationText(h))),
			]),
		)
	);
}
export const annotationAnchor = (h: Highlight, asin: string) =>
	"ks-" + annotationKey(h, asin).slice(3);
export function uniqueAnnotations(
	highlights: Highlight[],
	asin: string,
): Highlight[] {
	const unique = new Map<string, Highlight>();
	const expanded = highlights.flatMap((h) => {
		if (h.parentAnnotationKey) return [h];
		if (!h.text?.trim()) {
			const { notes, ...source } = h;
			return [
				...new Set([...(notes ?? []), ...(h.note ? [h.note] : [])]),
			].map((note) => ({ ...source, note }));
		}
		const { note, notes, ...source } = h;
		const memos = [
			...new Set(
				[...(notes ?? []), ...(note ? [note] : [])].filter((n) =>
					n.trim(),
				),
			),
		];
		return [
			source,
			...memos.map((note) => ({
				...source,
				text: "",
				note,
				parentAnnotationKey: annotationKey(source, asin),
			})),
		];
	});
	for (const h of expanded) {
		if (annotationText(h).trim())
			unique.set(
				annotationKey(h, asin),
				unique.get(annotationKey(h, asin)) ?? h,
			);
	}
	return [...unique.values()];
}
export function renderAnnotation(h: Highlight, asin: string): string {
	if (h.text?.trim() && (h.note || h.notes?.length))
		return uniqueAnnotations([h], asin)
			.map((a) => renderAnnotation(a, asin))
			.join("\n\n");
	const location = annotationLocation(h.location);
	const numeric = /^\d+$/.test(location) ? location : "";
	const link = `kindle://book?action=open&asin=${encodeURIComponent(asin)}${numeric ? `&location=${numeric}` : ""}`;
	const quoted = annotationText(h)
		.split(/\r?\n/)
		.map((line) => `> ${line}`)
		.join("\n");
	return `${quoted}\n> [${h.location || "Kindle"}](${link})\n\n^${annotationAnchor(h, asin)}`;
}

export interface AnnotationCounts {
	highlights: number;
	standaloneNotes: number;
	attachedNotes: number;
}
export function countAnnotations(
	annotations: Highlight[],
	asin?: string,
): AnnotationCounts {
	const counts = { highlights: 0, standaloneNotes: 0, attachedNotes: 0 };
	const groups = new Map<string, Highlight[]>();
	for (const h of annotations) {
		const key = asin ?? h.bookId;
		if (!groups.has(key)) groups.set(key, []);
		groups.get(key)!.push(h);
	}
	for (const [key, list] of groups)
		for (const h of uniqueAnnotations(list, key)) {
			if (h.text?.trim()) counts.highlights++;
			else if (h.parentAnnotationKey) counts.attachedNotes++;
			else counts.standaloneNotes++;
		}
	return counts;
}
